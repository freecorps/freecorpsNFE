const project = (lon: number, lat: number): [number, number] => [
  Math.round(((lon + 74.1) * 0.9703 * 14 + 8) * 10) / 10,
  Math.round(((5.4 - lat) * 14 + 8) * 10) / 10,
];

const points = arcs.map((arc) => {
  const n = arc.split(" ").map(Number);
  return Array.from({ length: n.length / 2 }, (_, i) => [n[2 * i]!, n[2 * i + 1]!] as const);
});

function ring(refs: number[]) {
  const out: (readonly [number, number])[] = [];
  for (const ref of refs) {
    const arc = ref < 0 ? [...points[~ref]!].reverse() : points[ref]!;
    out.push(...(out.length ? arc.slice(1) : arc));
  }
  return out;
}

function inside(x: number, y: number, poly: (readonly [number, number])[]) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]!;
    const [xj, yj] = poly[j]!;
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

