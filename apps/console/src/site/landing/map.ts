// Campinas, where the product's homologation runs: every route starts here.
const origin = project(-47.06, -22.91);
const step = 10;
const waves = 10;

const label = (name: string, [x, y]: readonly [number, number], side: Side, cls = "label") => {
  const [dx, dy, anchor] = {
    e: [8, 4, "start"],
    w: [-8, 4, "end"],
    n: [0, -9, "middle"],
    s: [0, 17, "middle"],
    sw: [4, 17, "end"],
  }[side] as [number, number, string];
  return `<text class="${cls}" x="${x + dx}" y="${y + dy}" text-anchor="${anchor}">${name}</text>`;
};

// Brazil with its 27 states, built at render time from the arcs above: a dot
// matrix per state, hairline borders, one route from Campinas to each capital.
// Everything is drawn lit, with the routes hidden; CSS replays it in ten waves
// (classes w0 to w9, by distance from Campinas) when the map comes into view,
// so the animation runs on a few dozen elements instead of on every dot. Each
// route shows only while it is drawn, and again when you hover its capital.
export function brazilMap() {
  const shapes = Object.entries(states).map(
    ([uf, rings]) => [uf, rings.map((refs) => ring(refs))] as const,
  );
  const dots = new Map<string, string[]>();
  for (let y = 12; y < 560; y += step)
    for (let x = 12; x < 545; x += step) {
      const state = shapes.find(([, rings]) => rings.some((poly) => inside(x, y, poly)));
      if (state) dots.set(state[0], [...(dots.get(state[0]) ?? []), `M${x} ${y}h0`]);
    }

  const far = Math.max(...capitals.map(([, , lon, lat]) => distance(project(lon, lat))));
  const land: string[] = [];
  const cities: string[] = [];
  const labels: string[] = [];
  for (const [uf, name, lon, lat, side] of capitals) {
    const at = project(lon, lat);
    const wave = `w${Math.min(waves - 1, Math.round((distance(at) / far) * (waves - 1)))}`;
    land.push(`<path class="land ${wave}" d="${(dots.get(uf) ?? []).join("")}"/>`);
    cities.push(
      `<g class="city"><title>${name} (${uf})</title>`,
      `<path class="route ${wave}" pathLength="1" d="${curve(at)}"/>`,
      `<circle class="ping ${wave}" cx="${at[0]}" cy="${at[1]}" r="3.4"/>`,
      `<circle class="hit" cx="${at[0]}" cy="${at[1]}" r="12"/>`,
      `<circle class="capital ${wave}" cx="${at[0]}" cy="${at[1]}" r="3.4"/></g>`,
    );
    if (side) labels.push(label(name, at, side, `label ${wave}${minor.has(uf) ? " minor" : ""}`));
  }

  const edges = points.map((arc, i) => ({ d: line(arc), edge: edge.has(i) }));
  const [ox, oy] = origin;
  const svg = [
    `<g class="map-land">${land.join("")}</g>`,
    `<path class="map-borders" d="${edges
      .filter((e) => !e.edge)
      .map((e) => e.d)
      .join("")}"/>`,
    `<path class="map-edge" d="${edges
      .filter((e) => e.edge)
      .map((e) => e.d)
      .join("")}"/>`,
    `<g class="map-cities">${cities.join("")}</g>`,
    `<circle class="origin-ring" cx="${ox}" cy="${oy}" r="9"/>`,
    `<circle class="origin" cx="${ox}" cy="${oy}" r="4.6"><title>Campinas (SP)</title></circle>`,
    `<g class="map-labels">${labels.join("")}${label("Campinas", origin, "w", "label origin-label")}</g>`,
  ];
  return { svg: svg.join(""), viewBox: "0 0 616 572" };
}

function distance([x, y]: readonly [number, number]) {
  return Math.hypot(x - origin[0], y - origin[1]);
}

// A shallow arc from Campinas, always bending the same way.
function curve([x, y]: readonly [number, number]) {
  const [ox, oy] = origin;
  const [mx, my] = [(ox + x) / 2, (oy + y) / 2];
  const bend = 0.2;
  const [cx, cy] = [mx - (y - oy) * bend, my + (x - ox) * bend];
  return `M${ox} ${oy}Q${cx.toFixed(1)} ${cy.toFixed(1)} ${x} ${y}`;
}
