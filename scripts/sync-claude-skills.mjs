// Generates the Claude Code entry points of the project skills. The skills live
// in `.agents/skills/<name>/SKILL.md` (Codex reads them there); Claude Code only
// discovers `.claude/skills/<name>/SKILL.md`. Each stub copies the original
// frontmatter verbatim, so name and description match, and points the agent at
// the real file. Regular files instead of symlinks: a checkout with
// core.symlinks=false (Windows) turns symlinks into one-line text files.
//   node scripts/sync-claude-skills.mjs          write, update and prune stubs
//   node scripts/sync-claude-skills.mjs --check  list problems, write nothing
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const sourceDirectory = ".agents/skills";
export const stubDirectory = ".claude/skills";
const generator = "scripts/sync-claude-skills.mjs";

/** Frontmatter block (`---` to `---`, both included) of a SKILL.md, LF-only, without a BOM. */
export function frontmatter(text) {
  const match = /^---[ \t]*\n[\s\S]*?\n---[ \t]*(?:\n|$)/.exec(
    text.replace(/^﻿/, "").replaceAll("\r\n", "\n"),
  );
  if (!match) throw new Error("SKILL.md without a YAML frontmatter block");
  return match[0].endsWith("\n") ? match[0] : `${match[0]}\n`;
}

/** Stub content for the skill `name` whose SKILL.md text is `text`. */
export function stub(name, text) {
  const source = `${sourceDirectory}/${name}`;
  return `${frontmatter(text)}
The full instructions of this skill live in \`${source}/SKILL.md\`.
Read that file in full now and follow it as if its content were here.
Relative links and supporting files it mentions resolve from \`${source}/\`, not from this directory.

This file is generated by \`${generator}\` from that SKILL.md.
Do not edit it by hand; run \`node ${generator}\` instead.
`;
}

/** Skill names: directories of the source (or links to one) with a SKILL.md, sorted. */
export function skillNames(root) {
  const base = join(root, sourceDirectory);
  return readdirSync(base)
    .filter(
      (name) =>
        statSync(join(base, name)).isDirectory() && existsSync(join(base, name, "SKILL.md")),
    )
    .sort();
}

/** Expected stubs: skill name to SKILL.md content. */
export function expectedStubs(root) {
  return new Map(
    skillNames(root).map((name) => {
      const path = `${sourceDirectory}/${name}/SKILL.md`;
      try {
        return [name, stub(name, readFileSync(join(root, path), "utf8"))];
      } catch (error) {
        throw new Error(`${path}: ${error.message}`, { cause: error });
      }
    }),
  );
}

/** Whether `path` is a directory holding exactly SKILL.md with `content`. */
function isCurrent(path, content) {
  const stat = lstatSync(path);
  if (!stat.isDirectory()) return false;
  const files = readdirSync(path);
  if (files.length !== 1 || files[0] !== "SKILL.md") return false;
  const file = join(path, "SKILL.md");
  return lstatSync(file).isFile() && readFileSync(file, "utf8") === content;
}

/**
 * Differences between `.claude/skills` and the expected stubs: `missing`
 * (no entry), `stale` (wrong content, a symlink, a plain file or extra files)
 * and `extra` (an entry with no matching skill). Names are sorted.
 */
export function inspect(root) {
  const expected = expectedStubs(root);
  const base = join(root, stubDirectory);
  const present = existsSync(base) ? readdirSync(base).sort() : [];
  const missing = [...expected.keys()].filter((name) => !present.includes(name));
  const stale = present.filter(
    (name) => expected.has(name) && !isCurrent(join(base, name), expected.get(name)),
  );
  const extra = present.filter((name) => !expected.has(name));
  return { expected, missing, stale, extra };
}

function remove(path) {
  if (lstatSync(path).isSymbolicLink()) unlinkSync(path);
  else rmSync(path, { recursive: true, force: true });
}

/**
 * Whether an extra entry is ours to delete: an old link (a symlink, or the
 * one-line file it becomes with core.symlinks=false) or a generated stub. Any
 * other file or skill someone keeps in `.claude/skills` is reported, never deleted.
 */
function generated(path) {
  const stat = lstatSync(path);
  if (stat.isSymbolicLink()) return true;
  // With core.symlinks=false a link is a file holding only its target; any other file stays.
  if (stat.isFile())
    return /^(?:\.\.\/)+\.agents\/skills\/[^/\s]+\/?\s*$/.test(readFileSync(path, "utf8"));
  const file = join(path, "SKILL.md");
  return existsSync(file) && readFileSync(file, "utf8").includes(`generated by \`${generator}\``);
}

/**
 * Writes missing and stale stubs and removes the extra entries it generated;
 * returns `inspect`, so any other extra entry still shows up as a problem.
 */
export function sync(root) {
  const result = inspect(root);
  const base = join(root, stubDirectory);
  for (const name of result.extra) if (generated(join(base, name))) remove(join(base, name));
  for (const name of [...result.stale, ...result.missing]) {
    const path = join(base, name);
    if (result.stale.includes(name)) remove(path);
    mkdirSync(path, { recursive: true });
    writeFileSync(join(path, "SKILL.md"), result.expected.get(name), "utf8");
  }
  return result;
}

/** One line per problem, `kind path`, for the CLI and the tests. */
export function problems({ missing, stale, extra }) {
  return [
    ...missing.map((name) => `missing ${stubDirectory}/${name}`),
    ...stale.map((name) => `stale ${stubDirectory}/${name}`),
    ...extra.map((name) => `extra ${stubDirectory}/${name}`),
  ];
}

function main(argv) {
  const root = fileURLToPath(new URL("../", import.meta.url));
  if (argv.includes("--check")) {
    const found = problems(inspect(root));
    if (found.length) {
      console.error(found.join("\n"));
      console.error(`Run \`node ${generator}\` to update ${stubDirectory}.`);
      process.exitCode = 1;
    } else console.log(`${stubDirectory} is up to date.`);
    return;
  }
  const result = sync(root);
  const changed = problems(result);
  console.log(
    changed.length
      ? `Updated ${stubDirectory}:\n${changed.join("\n")}`
      : `${stubDirectory} is up to date.`,
  );
  console.log(`${result.expected.size} skills.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1])
  main(process.argv.slice(2));
